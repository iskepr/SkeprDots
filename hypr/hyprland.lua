hl.on("hyprland.start", function()
    hl.exec_cmd("dbus-update-activation-environment --systemd --all")
    hl.exec_cmd("systemctl --user import-environment WAYLAND_DISPLAY XDG_CURRENT_DESKTOP")
    hl.exec_cmd("systemctl --user start hyprland-session.target")
    hl.exec_cmd("systemctl --user start hyprpolkitagent")
    hl.exec_cmd("systemctl --user restart xdg-desktop-portal-hyprland")
    hl.exec_cmd("$HOME/.config/hypr/initial-boot.sh")
    hl.exec_cmd("xhost +local:root")
    hl.exec_cmd("sleep 1 && pactl set-source-port alsa_input.pci-0000_06_00.6.analog-stereo analog-input-mic")
    hl.exec_cmd("kdeconnectd")
    hl.exec_cmd("blueman-applet")
    hl.exec_cmd("bash -c 'wl-paste --watch cliphist store &'")
    hl.exec_cmd("ln -sf /run/media/skepr/Data/Github/ ~/Documents/Github")
