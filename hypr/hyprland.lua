-- === Focus & Window Movement (Loops) ===
local dirs = { left = "l", down = "d", up = "u", right = "r", H = "l", J = "d", K = "u", L = "r", P = "r" }
for key, dir in pairs(dirs) do
    if key ~= "L" then hl.bind(mainMod .. " + " .. key, hl.dsp.focus({ direction = dir })) end
    if key ~= "P" and key ~= "L" then hl.bind(mainMod .. " + SHIFT + " .. key, hl.dsp.window.move({ direction = dir })) end
    hl.bind(mainMod .. " + CTRL + " .. key, hl.dsp.focus({ monitor = dir }))
    hl.bind(mainMod .. " + SHIFT + CTRL + " .. key, hl.dsp.window.move({ monitor = dir }))
end

